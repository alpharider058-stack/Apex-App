async function translateBatch(texts) {
  const sep = '\n ||| \n'
  const joined = texts.join(sep)
  const url =
    'https://translate.googleapis.com/translate_a/single?client=gtx&sl=en&tl=es&dt=t&q=' +
    encodeURIComponent(joined)
  const res = await fetch(url)
  const json = await res.json()
  const full = json[0].map((x) => x[0]).join('')
  return full.split(/\s*\|\|\|\s*/)
}

// Translate instructions in batches of 8 exercises
for (let i = 0; i < data.length; i += 8) {
  const slice = data.slice(i, i + 8)
  const flat = []
  const counts = []
  for (const ex of slice) {
    ex.en = ex.en || ex.name
    ex.name = translateExerciseName(ex.en)
    counts.push(ex.instructions.length)
    flat.push(...ex.instructions)
  }
  const translated = await translateBatch(flat)
  let k = 0
  for (let j = 0; j < slice.length; j++) {
    const c = counts[j]
    slice[j].instructions = translated.slice(k, k + c).map((line) => line.trim())
    k += c
  }
  if ((i + 8) % 64 === 0 || i + 8 >= data.length) {
    console.log(`Translated ${Math.min(data.length, i + 8)}/${data.length}`)
  }
}

